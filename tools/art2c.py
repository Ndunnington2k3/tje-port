#!/usr/bin/env python3
"""Convert the port's own artwork (art/*.png) to C arrays in src/game/art_*.c.

Each colour in the PNG must be one the Genesis can show (components on the
0, 36, 72, 109, 145, 182, 218, 255 scale); fully transparent pixels become
colour 0. --map gives each colour (rrggbb) its palette slot.

    python tools/art2c.py art/load_title.png load_title \
        --map 00ffb6=12,246d48=13,00b6ff=14,004800=15
"""
import argparse
from PIL import Image

LEVELS = [0, 36, 72, 109, 145, 182, 218, 255]


def genesis_word(rgb):
    out = 0
    for shift, v in zip((1, 5, 9), rgb):
        if v not in LEVELS:
            raise SystemExit(f'colour {rgb} is not a Genesis colour (component {v})')
        out |= LEVELS.index(v) << shift
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('png')
    ap.add_argument('name')
    ap.add_argument('--map', required=True, help='rrggbb=slot,...')
    ap.add_argument('--out')
    a = ap.parse_args()
    im = Image.open(a.png).convert('RGBA')
    w, h = im.size
    slots = {}
    for item in a.map.split(','):
        hexc, slot = item.split('=')
        slots[tuple(int(hexc[i:i + 2], 16) for i in (0, 2, 4))] = int(slot)
    px = []
    for y in range(h):
        for x in range(w):
            r, g, b, al = im.getpixel((x, y))
            if al == 0:
                px.append(0)
            elif (r, g, b) in slots:
                px.append(slots[(r, g, b)])
            else:
                raise SystemExit(f'pixel {x},{y}: colour {(r, g, b)} has no slot in --map')
    out = a.out or f'src/game/art_{a.name}.c'
    with open(out, 'w') as f:
        f.write(f'/* Generated by tools/art2c.py from {a.png} - port artwork, not from the game. */\n')
        f.write('#include "art.h"\n\n')
        f.write(f'static const unsigned char pixels[{w * h}] = {{\n')
        for y in range(h):
            f.write('    ' + ','.join(str(p) for p in px[y * w:(y + 1) * w]) + ',\n')
        f.write('};\n\n')
        pal = {}
        for rgb, slot in slots.items():
            pal[slot] = genesis_word(rgb)
        f.write(f'const ArtImage art_{a.name} = {{\n    {w}, {h},\n    {{')
        f.write(', '.join(f'{{{s}, 0x{pal[s]:04X}}}' for s in sorted(pal)))
        f.write(f'}}, {len(pal)},\n    pixels\n}};\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
